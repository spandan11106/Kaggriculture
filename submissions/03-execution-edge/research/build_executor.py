"""Build the Maximal Executor agent = kyle's solved tape (build+farm actions) +
a drain-aware premium-sell pacer with opponent-dump front-running.

The farm actions (water/feed/harvest/care/place) and all market BUYs/HIREs/LAND
come VERBATIM from kyle_r33's proven tape (byte-identical build to v19). ONLY the
premium SELL orders (MILK/WOOL/STRAWBERRY/MELON) are replaced by a policy that
paces sells to the town-drain recovery so premiums don't crash to the $1 floor.

Regenerate:  python submissions/03-execution-edge/research/build_executor.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SUB = os.path.dirname(HERE)
KYLE = os.path.join(SUB, "..", "02-kyle-r33", "main.py")
OUT = os.path.join(SUB, "main.py")

# The pacer knobs live here so sweeps can regenerate variants (see loss forensics).
# v2: TWAP milk/wool within the day (never hoard -> no overflow), grab extra when the
# price is genuinely high, front-run the opponent's visible dump, liquidate at the end.
# Strawberry/melon are LEFT TO THE TAPE (they never floor; pacing them only lost units).
PARAMS = dict(
    pace_items=["MILK", "WOOL"],  # which premiums the pacer re-times (rest left to the tape)
    good_price_frac=0.95,  # price >= this*base counts as "high" -> sell an extra chunk
    grab_floor=0.80,       #   when grabbing, sell down only to this*base (keep price up)
    hard_cap=40,           # max units of milk/wool to sell in a single turn
    endgame_day=29,        # from this day on, dump all remaining milk/wool
    late_day=28, late_hour=14,  # partial pre-clear starts here
    frontrun_exposure=20,  # opponent visible holding >= this many units of the premium ->
    frontrun_extra=6,      #   sell this many extra units now, ahead of their crash
)

BODY = r'''# Submission 3 — Maximal Executor  (GENERATED by research/build_executor.py; do not edit by hand)
# kyle_r33's solved tape (build + farm actions + buys/hires) with the premium SELL
# orders replaced by a drain-aware pacer + opponent-dump front-runner. Only market
# timing of MILK/WOOL/STRAWBERRY/MELON changes; the build is byte-identical to v19/kyle.
import json, zlib, base64, math

_TAPE = json.loads(zlib.decompress(base64.b85decode(_BLOB_)))

MARKET_I0 = 10000
PRICE_FLOOR = 1
# (base, T, below_func, below_target, above_func, above_target) copied verbatim from env_ref.
_MP = {
    "WHEAT":      ("sqrt", 0.80, "log",    0.20, 25,  400),
    "CARROT":     ("log",  0.20, "sqrt",   0.70, 35,  450),
    "TOMATO":     ("linear",0.40,"sqrt",   0.60, 60,  200),
    "STRAWBERRY": ("sqrt", 0.70, "linear", 1.60, 120, 100),
    "MELON":      ("log",  0.20, "sq",     3.60, 250, 300),
    "EGG":        ("linear",0.40,"log",    0.20, 50,  332),
    "MILK":       ("sqrt", 0.60, "linear", 1.60, 160, 122),
    "WOOL":       ("log",  0.20, "sq",     3.20, 200, 105),
    "FERTILIZER": ("linear",0.40,"linear", 0.40, 100, 200),
}
def _shape(f, x):
    x = 0.0 if x < 0 else x
    if f == "linear": return x
    if f == "sq":     return x * x
    if f == "sqrt":   return math.sqrt(x)
    if f == "log":    return math.log(1.0 + x)
    return x
def _price(item, inv):
    bf, bt, af, at, base, T = _MP[item]
    if inv < MARKET_I0:
        amp = bt * base / _shape(bf, T); pr = base + amp * _shape(bf, MARKET_I0 - inv)
    else:
        amp = at * base / _shape(af, T); pr = base - amp * _shape(af, inv - MARKET_I0)
    return max(PRICE_FLOOR, int(round(pr)))

_PACE = _PACE_ITEMS_           # premiums the pacer re-times; rest of the tape's sells kept verbatim
_ANIMAL_PROD = {"COW": "MILK", "SHEEP": "WOOL", "GOOSE": "EGG"}

_GOOD_FRAC   = _GOOD_FRAC_
_GRAB_FLOOR  = _GRAB_FLOOR_
_HARD_CAP    = _HARD_CAP_
_ENDGAME_DAY = _ENDGAME_DAY_
_LATE_DAY    = _LATE_DAY_
_LATE_HOUR   = _LATE_HOUR_
_FR_EXP      = _FR_EXP_
_FR_EXTRA    = _FR_EXTRA_

def _opp_exposure(farms, player):
    exp = {k: 0 for k in _PACE}
    if not farms or len(farms) < 2: return exp
    opp = farms[1 - player] if player in (0, 1) else farms[0]
    for row in opp.get("tiles", []) or []:
        for t in row:
            if not isinstance(t, dict): continue
            an = t.get("animal")
            if an in _ANIMAL_PROD:
                prod = _ANIMAL_PROD[an]
                if prod in exp: exp[prod] += 1 + int(t.get("yield_units", 0) or 0)
    return exp

def _sellable_qty(item, inv0, min_price, shed_qty, hard_cap):
    """Units we can sell this turn while keeping the realized price >= min_price."""
    inv = inv0; k = 0
    while k < shed_qty and k < hard_cap:
        pr = _price(item, inv)
        if pr < min_price: break
        k += 1
        if pr > PRICE_FLOOR: inv += 1
    return k

def _ceil_div(a, b):
    b = b if b else 1
    return -(-a // b)

def _pace_sells(day, hour, inv, shed, exposure, slots):
    """TWAP milk/wool over the day (never hoard -> no overflow), grab extra when the price
    is high, front-run the opponent's visible dump, and fully liquidate at the end."""
    if slots <= 0: return []
    endgame = day >= _ENDGAME_DAY
    late = (day > _LATE_DAY) or (day == _LATE_DAY and hour >= _LATE_HOUR)
    tld = max(1, 24 - hour)                            # turns left in the day, incl. this one
    orders = []
    for item in _PACE:
        if len(orders) >= slots: break
        q = int(shed.get(item, 0) or 0)
        if q <= 0: continue
        if endgame:
            orders.append(["SELL", item, int(q)])     # dump everything (no cap)
            continue
        base = _MP[item][4]
        inv0 = int(inv.get(item, MARKET_I0) or MARKET_I0)
        price = _price(item, inv0)
        denom = min(tld, 6) if late else tld           # compress clearance in the final hours
        k = _ceil_div(q, denom)                        # base TWAP rate
        if price >= _GOOD_FRAC * base:                 # price is high -> grab a bigger chunk
            k = max(k, _sellable_qty(item, inv0, _GRAB_FLOOR * base, q, _HARD_CAP))
        if exposure.get(item, 0) >= _FR_EXP:           # front-run an imminent opponent dump
            k += _FR_EXTRA
        k = min(k, _HARD_CAP, q)
        if k > 0:
            orders.append(["SELL", item, int(k)])
    return orders[:slots]

def agent(obs, config=None):
    try:
        day = int(obs.get("day", 0) or 0); hour = int(obs.get("hour", 0) or 0)
        step = day * 24 + hour
        if step >= len(_TAPE): step = len(_TAPE) - 1
        tp = _TAPE[step]
        market = [o for o in (tp.get("market", []) or [])
                  if not (o and o[0] == "SELL" and len(o) > 1 and o[1] in _PACE)]
        slots = max(0, 10 - len(market))
        mkt = obs.get("market", {}) or {}
        inv = mkt.get("inventory", {}) or {}
        shed = (obs.get("private", {}) or {}).get("shed", {}) or {}
        exposure = _opp_exposure(obs.get("farms", []) or [], int(obs.get("player", 0) or 0))
        market = market + _pace_sells(day, hour, inv, shed, exposure, slots)
        return {"farmer": tp.get("farmer", ["PASS"]), "hands": tp.get("hands", []), "market": market}
    except Exception:
        s = min(int(obs.get("day", 0) or 0) * 24 + int(obs.get("hour", 0) or 0), len(_TAPE) - 1)
        return _TAPE[s]
'''


def main():
    src = open(KYLE).read()
    m = re.search(r"b85decode\('(.+?)'\)", src, re.S)
    if not m:
        raise SystemExit("could not find kyle tape blob")
    blob = m.group(1)
    body = (BODY
            .replace("_BLOB_", "'" + blob + "'")
            .replace("_PACE_ITEMS_", repr(PARAMS["pace_items"]))
            .replace("_GOOD_FRAC_", repr(PARAMS["good_price_frac"]))
            .replace("_GRAB_FLOOR_", repr(PARAMS["grab_floor"]))
            .replace("_HARD_CAP_", repr(PARAMS["hard_cap"]))
            .replace("_ENDGAME_DAY_", repr(PARAMS["endgame_day"]))
            .replace("_LATE_DAY_", repr(PARAMS["late_day"]))
            .replace("_LATE_HOUR_", repr(PARAMS["late_hour"]))
            .replace("_FR_EXP_", repr(PARAMS["frontrun_exposure"]))
            .replace("_FR_EXTRA_", repr(PARAMS["frontrun_extra"]))
            )
    with open(OUT, "w") as f:
        f.write(body)
    print("wrote", OUT, "(%d bytes)" % len(body))
    print("params:", PARAMS)


if __name__ == "__main__":
    main()
