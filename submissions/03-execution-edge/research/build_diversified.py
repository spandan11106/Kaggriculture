"""Build the DIVERSIFIED agent = kyle's proven tape with N marginal cow-tiles converted
IN PLACE to goose-coops (BUILD_PASTURE->BUILD_COOP, PLACE COW->PLACE GOOSE, BUY_ANIMAL
COW->GOOSE), plus an egg-selling overlay. The engine's FEED/CARE/HARVEST are animal-agnostic,
so kyle's recorded feeding/watering/routing keeps working; only what's produced changes:
N geese sell ~54 eggs/season each into the UNCONTESTED egg market (0/14 opponents supply eggs).

Requires research/animal_tiles.json (from find_animal_tiles.py).
Regenerate: python submissions/03-execution-edge/research/build_diversified.py [N]
"""
import os, sys, re, json, zlib, base64

HERE = os.path.dirname(os.path.abspath(__file__))
SUB = os.path.dirname(HERE)
KYLE = os.path.join(SUB, "..", "02-kyle-r33", "main.py")
OUT = os.path.join(SUB, "main.py")
N = int(sys.argv[1]) if len(sys.argv) > 1 else 3     # cows to convert -> geese
WHICH = sys.argv[2] if len(sys.argv) > 2 else "early"  # "early" cows (placed day 0) = more egg-days

# ---- load kyle tape ----
ksrc = open(KYLE).read()
blob = re.search(r"b85decode\('(.+?)'\)", ksrc, re.S).group(1)
TAPE = json.loads(zlib.decompress(base64.b85decode(blob.encode())))

# ---- pick the N latest-placed cows + N latest cow-buys ----
tiles = json.load(open(os.path.join(HERE, "animal_tiles.json")))
cows = sorted(tiles["cows"], key=lambda t: t["place"]["step"])
cow_buy_steps = [i for i, a in enumerate(TAPE)
                 for o in a.get("market", []) if o and o[0] == "BUY_ANIMAL" and o[1] == "COW"]
if WHICH == "early":
    convert, buy_convert = cows[:N], cow_buy_steps[:N]
else:
    convert, buy_convert = cows[-N:], cow_buy_steps[-N:]
print(f"converting {N} {WHICH} cows -> geese")
print(f"  tiles:      {[t['pos'] for t in convert]}")
print(f"  buy steps:  {buy_convert}  (of {cow_buy_steps})")


def _actor(step, idx):
    """Return (list-container, key) for the actor's action so we can edit it."""
    a = TAPE[step]
    if idx == 0:
        return a, "farmer"
    return a["hands"], idx - 1


def _get(step, idx):
    c, k = _actor(step, idx)
    return c[k]


def _set(step, idx, val):
    c, k = _actor(step, idx)
    c[k] = val


# ---- apply conversions with verification ----
pickup_groups = {}   # (step,idx) -> [tiles] ; one PICKUP COW n can load n animals for n tiles
for t in convert:
    bs, bi = t["build"]["step"], t["build"]["idx"]
    ps, pi = t["place"]["step"], t["place"]["idx"]
    assert _get(bs, bi)[0] == "BUILD_PASTURE", f"build mismatch @{bs}/{bi}: {_get(bs,bi)}"
    assert _get(ps, pi)[:2] == ["PLACE", "COW"], f"place mismatch @{ps}/{pi}: {_get(ps,pi)}"
    assert t.get("pickup"), f"no matched PICKUP for tile {t['pos']}"
    _set(bs, bi, ["BUILD_COOP"])
    _set(ps, pi, ["PLACE", "GOOSE"])
    pickup_groups.setdefault((t["pickup"]["step"], t["pickup"]["idx"]), []).append(t)

for (us, ui), ts in pickup_groups.items():
    old = _get(us, ui)
    assert old[:2] == ["PICKUP", "COW"], f"pickup mismatch @{us}/{ui}: {old}"
    k = old[2] if len(old) > 2 else 1
    assert k == len(ts), (f"PICKUP COW {k} @{us}/{ui} loads {k} animals but {len(ts)} converted "
                          f"tiles share it — splitting a mixed pickup is unsupported; pick different N")
    _set(us, ui, ["PICKUP", "GOOSE"] + list(old[2:]))   # preserve count

for step in buy_convert:
    mkt = TAPE[step]["market"]
    done = False
    for o in mkt:
        if o and o[0] == "BUY_ANIMAL" and o[1] == "COW":
            o[1] = "GOOSE"
            done = True
            break
    assert done, f"no BUY_ANIMAL COW at step {step}"

# sanity: build tally after conversion
from collections import Counter
tally = Counter()
for a in TAPE:
    for o in a.get("market", []):
        if o and o[0] == "BUY_ANIMAL":
            tally[o[1]] += o[2] if len(o) > 2 else 1
    for act in [a.get("farmer", [])] + a.get("hands", []):
        if act and act[0] in ("BUILD_COOP", "BUILD_PASTURE"):
            tally[act[0]] += 1
        if act and act[0] == "PLACE" and len(act) > 1:
            tally["PLACE_" + act[1]] += 1
print(f"  post-convert tally: COW={tally['COW']} GOOSE={tally['GOOSE']} SHEEP={tally['SHEEP']} "
      f"COOP={tally['BUILD_COOP']} PASTURE={tally['BUILD_PASTURE']} "
      f"PLACE_GOOSE={tally['PLACE_GOOSE']} PLACE_COW={tally['PLACE_COW']}")

# ---- re-encode + emit main.py with egg-sell overlay ----
new_blob = base64.b85encode(zlib.compress(json.dumps(TAPE).encode(), 9)).decode()

BODY = '''# Submission 3 — DIVERSIFIED  (GENERATED by research/build_diversified.py; do not edit by hand)
# kyle's proven tape with %d marginal cows converted IN PLACE to goose-coops, plus an
# egg-selling overlay. Geese sell into the uncontested egg market (0/14 opponents supply eggs).
import json, zlib, base64
_TAPE = json.loads(zlib.decompress(base64.b85decode(_BLOB_)))

def agent(obs, config=None):
    try:
        day = int(obs.get("day", 0) or 0); hour = int(obs.get("hour", 0) or 0)
        step = day * 24 + hour
        if step >= len(_TAPE): step = len(_TAPE) - 1
        tp = _TAPE[step]
        market = list(tp.get("market", []) or [])
        shed = (obs.get("private", {}) or {}).get("shed", {}) or {}
        eggs = int(shed.get("EGG", 0) or 0)
        if eggs > 0 and len(market) < 10:          # sell all eggs (uncontested -> no floor risk)
            market = market + [["SELL", "EGG", eggs]]
        return {"farmer": tp.get("farmer", ["PASS"]), "hands": tp.get("hands", []), "market": market}
    except Exception:
        s = min(int(obs.get("day", 0) or 0) * 24 + int(obs.get("hour", 0) or 0), len(_TAPE) - 1)
        return _TAPE[s]
''' % N

body = BODY.replace("_BLOB_", "'" + new_blob + "'")
open(OUT, "w").write(body)
print(f"wrote {OUT} ({len(body)} bytes)")
